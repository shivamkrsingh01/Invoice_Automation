"""Report API routes for generating invoice summary reports."""

from datetime import date, datetime, timedelta
from typing import Optional
from fastapi import APIRouter, HTTPException, Query, Response, Depends
from fastapi.responses import StreamingResponse
from pydantic import BaseModel
from app.services.report_service import ReportService
from app.services.auth_service import require_auth
from app.utils.logging_config import logger

router = APIRouter()


class ReportRequest(BaseModel):
    """Request model for report generation."""
    period: str  # "weekly", "monthly", "custom"
    start_date: Optional[str] = None  # ISO format date string
    end_date: Optional[str] = None  # ISO format date string


def get_date_range(period: str, start_date: Optional[str] = None, end_date: Optional[str] = None) -> tuple[date, date]:
    """Calculate date range based on period type."""
    today = date.today()
    
    if period == "weekly":
        # Last 7 days
        start = today - timedelta(days=7)
        end = today
    elif period == "monthly":
        # Last 30 days
        start = today - timedelta(days=30)
        end = today
    elif period == "custom":
        if not start_date or not end_date:
            raise HTTPException(status_code=400, detail="start_date and end_date required for custom period")
        try:
            start = datetime.fromisoformat(start_date).date()
            end = datetime.fromisoformat(end_date).date()
        except ValueError:
            raise HTTPException(status_code=400, detail="Invalid date format. Use ISO format (YYYY-MM-DD)")
        
        if start > end:
            raise HTTPException(status_code=400, detail="start_date must be before or equal to end_date")
    else:
        raise HTTPException(status_code=400, detail="Invalid period. Use 'weekly', 'monthly', or 'custom'")
    
    return start, end


@router.post("/reports/data")
async def get_report_data(
    request: ReportRequest,
    user: str = Depends(require_auth)
):
    """Get report data for the specified date range."""
    try:
        from app.services.postgres_storage_service import PostgresStorageService
        from app.config.settings import settings
        
        # Create a new postgres service instance
        postgres_service = PostgresStorageService()
        
        # Calculate date range
        start_date, end_date = get_date_range(
            request.period,
            request.start_date,
            request.end_date
        )
        
        # Generate report data
        report_service = ReportService(postgres_service.pool)
        report_data = report_service.get_report_data(start_date, end_date)
        
        logger.info(f"Report data generated by {user} for period {request.period}")
        return report_data
        
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to generate report data: {str(e)}")
        raise HTTPException(status_code=500, detail=str(e))


@router.post("/reports/pdf")
async def download_pdf_report(
    request: ReportRequest,
    user: str = Depends(require_auth)
):
    """Generate and download a PDF report."""
    try:
        from app.services.postgres_storage_service import PostgresStorageService
        
        postgres_service = PostgresStorageService()
        
        # Calculate date range
        start_date, end_date = get_date_range(
            request.period,
            request.start_date,
            request.end_date
        )
        
        # Generate report data
        report_service = ReportService(postgres_service.pool)
        report_data = report_service.get_report_data(start_date, end_date)
        
        # Generate PDF
        pdf_buffer = report_service.generate_pdf_report(report_data)
        
        # Create filename
        filename = f"invoice_report_{request.period}_{start_date}_to_{end_date}.pdf"
        
        logger.info(f"PDF report downloaded by {user} for period {request.period}")
        
        return StreamingResponse(
            pdf_buffer,
            media_type="application/pdf",
            headers={"Content-Disposition": f"attachment; filename={filename}"}
        )
        
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to generate PDF report: {str(e)}")
        raise HTTPException(status_code=500, detail=str(e))


